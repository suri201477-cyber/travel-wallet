_COUNTRIES: dict[str, tuple[str, str]] = {}
_KNOWN_CURRENCIES: set[str] = set()
_CURRENCY_TITLES: dict[str, str] = {}

for _aliases, _title, _code in _ENTRIES:
    _KNOWN_CURRENCIES.add(_code)
    _CURRENCY_TITLES.setdefault(_code, _title)
    for _alias in _aliases:
        _COUNTRIES[_alias] = (_title, _code)

_CURRENCY_TITLES["EUR"] = "Еврозона"
_CURRENCY_TITLES["USD"] = "США"
_CURRENCY_TITLES["GBP"] = "Великобритания"


def normalize_place(text: str) -> str:
    cleaned = text.strip().lower().replace("ё", "е")
    cleaned = cleaned.replace("-", " ")
    cleaned = re.sub(r"[^a-zа-я0-9 ]", "", cleaned)
    return re.sub(r"\s+", " ", cleaned).strip()


def resolve_place(text: str) -> tuple[str, str] | None:
    """Возвращает (название, код валюты) или None, если страну не удалось разобрать."""
    cleaned = normalize_place(text)
    if not cleaned:
        return None
    if cleaned in _COUNTRIES:
        return _COUNTRIES[cleaned]
    compact = cleaned.replace(" ", "")
    if re.fullmatch(r"[a-z]{3}", compact) and compact.upper() in _KNOWN_CURRENCIES:
        code = compact.upper()
        return _CURRENCY_TITLES.get(code, code), code
    return None
